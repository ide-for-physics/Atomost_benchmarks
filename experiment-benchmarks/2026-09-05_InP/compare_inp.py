#!/usr/bin/env python3
"""Compare the InP Gamma-c coherent-phonon kernel (96^3, 2026-09-04) with experiment.

What is compared (and what is not):
  1. Pump-energy structure: the basis-independent degenerate-TO invariant of the calculated
     kernel is placed on the experimental energy scale with ONE rigid shift equal to the
     PBE band-gap error (E_gap,exp - E_gap,PBE), and overlaid with the measured InP
     dielectric function (Aspnes & Studna 1983, spectroscopic ellipsometry, 1.5-6.0 eV).
     The kernel's resonant denominators are the interband energies, so its peaks must sit at
     the measured E1 and E2 critical points if the electronic structure is right.  No
     amplitude scale is compared (there is no measured pump-energy scan of a coherent
     phonon in bulk InP).
  2. Phonon frequencies: the calculated Gamma-point optical mode (retained DFPT phonons)
     versus Raman TO/LO of bulk InP and of the InP nanowires used in the only located
     time-domain coherent-TO-phonon experiment (Mante et al., ACS Photonics 2020).
  3. Mechanism: Mante et al. find the coherent TO amplitude independent of doping (surface
     field), i.e. generated by a second-order (Raman-type) process - the process computed
     here - while the modes inside the Reststrahlen band scale with the surface field.
Status label: resonance-structure and mechanism consistency, NOT an amplitude validation.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[2] / "materials/InP/reuse_20260902/postprocess"))
from plot_inp_kernel import parse_gamma  # noqa: E402

EV_UM = 1.239841984                      # eV * um
E_GAP_EXP_300K = 1.344                   # eV, Vurgaftman, Meyer, Ram-Mohan, JAP 89, 5815 (2001)
E_GAP_PBE_PATH = 0.446                   # eV, fresh scalar DFT band reference, 703-point path (job 21722211)
RAMAN_BULK_TO = 303.7                    # cm-1, Mooradian & Wright, Solid State Commun. 4, 431 (1966)
RAMAN_BULK_LO = 345.0
NW_TO_THZ, NW_LO_THZ = 8.9, 10.3         # Mante et al. 2020, Fig. 3b (nanowire Raman / pump-probe)
THZ_TO_CM1 = 33.35641
MEV_TO_CM1 = 8.06554394
PUMP_MANTE_EV = EV_UM / 0.550            # 550 nm, 35 fs pump (coherent TO via second-order process)
PUMP_PFEIFER_EV = 2.0                    # Pfeifer et al. 1992, LO via surface-field screening (GaAs data)


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def read_aspnes_yml(path: Path):
    rows = []
    in_data = False
    for line in path.read_text().splitlines():
        if line.strip().startswith("data:"):
            in_data = True
            continue
        if in_data:
            parts = line.split()
            if len(parts) == 3:
                try:
                    rows.append([float(p) for p in parts])
                except ValueError:
                    pass
    arr = np.asarray(rows)
    lam, n, k = arr[:, 0], arr[:, 1], arr[:, 2]
    e = EV_UM / lam
    order = np.argsort(e)
    e, n, k = e[order], n[order], k[order]
    eps2 = 2 * n * k
    eps1 = n**2 - k**2
    return e, n, k, eps1, eps2


def local_maxima(x, y, lo, hi):
    out = []
    for i in range(1, len(x) - 1):
        if lo <= x[i] <= hi and y[i] > y[i - 1] and y[i] >= y[i + 1]:
            out.append((float(x[i]), float(y[i])))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("gamma", type=Path)
    ap.add_argument("--aspnes", type=Path, default=HERE / "InP_Aspnes1983_nk.yml")
    ap.add_argument("--output-dir", type=Path, default=HERE)
    args = ap.parse_args()

    # --- experiment: dielectric function -> critical points
    e_exp, n, k, eps1, eps2 = read_aspnes_yml(args.aspnes)
    csv_path = args.output_dir / "inp_aspnes1983_eps.csv"
    with csv_path.open("w", newline="") as f:
        f.write("# Source: D. E. Aspnes and A. A. Studna, Phys. Rev. B 27, 985 (1983); <100> undoped InP, room temperature\n")
        f.write("# Data file: refractiveindex.info database (CC0), database/data/main/InP/nk/Aspnes.yml; E = 1.239841984/lambda(um); eps2 = 2 n k\n")
        w = csv.writer(f)
        w.writerow(["photon_energy_ev", "n", "k", "eps1", "eps2"])
        for row in zip(e_exp, n, k, eps1, eps2):
            w.writerow([f"{v:.5f}" for v in row])
    exp_peaks = local_maxima(e_exp, eps2, 1.5, 6.0)
    exp_peaks_sorted = sorted(exp_peaks, key=lambda t: -t[1])
    e1_exp = min(p[0] for p in exp_peaks_sorted[:2])
    e2_exp = max(p[0] for p in exp_peaks_sorted[:2])

    # --- calculation: invariant kernel
    modes, freqs, w, g = parse_gamma(args.gamma)
    inv = np.sqrt((np.abs(g) ** 2).sum(axis=(0, 2)))
    shift = E_GAP_EXP_300K - E_GAP_PBE_PATH
    w_shift = w + shift
    calc_peaks = sorted(local_maxima(w, inv, 1.0, 6.0), key=lambda t: -t[1])
    main_peak = calc_peaks[0]
    # strongest secondary above 3.5 eV (PBE scale) = E2-like feature
    sec = [p for p in calc_peaks if p[0] > 3.5]
    sec_peak = sec[0] if sec else (float("nan"), float("nan"))
    calc_freq_cm1 = float(freqs[0] * MEV_TO_CM1)
    inv_at = lambda e_exp_scale: float(np.interp(e_exp_scale - shift, w, inv))

    metrics = {
        "status": "resonance_structure_and_mechanism_consistency_not_amplitude_validation",
        "calculation": {
            "source": str(args.gamma.resolve()), "sha256": sha256(args.gamma),
            "mesh": "96x96x96 fine k, 300 K, degaussw 0.03 eV, Gamma-c only, 13 Wannier bands, scalar",
            "quantity": "sqrt(sum over 3 degenerate TO modes and 9 channels |Gamma|^2)",
            "pbe_direct_gap_ev": E_GAP_PBE_PATH,
            "main_peak_pbe_ev": main_peak[0], "main_peak_A2_per_eV": main_peak[1],
            "secondary_peak_pbe_ev": sec_peak[0], "secondary_peak_A2_per_eV": sec_peak[1],
            "optical_mode_mev": float(freqs[0]), "optical_mode_cm-1": calc_freq_cm1,
        },
        "scissor": {
            "rigid_shift_ev": shift,
            "definition": "experimental 300 K gap (1.344 eV, Vurgaftman 2001) minus PBE direct gap on the 703-point path (0.446 eV); applied to the photon axis only",
            "main_peak_shifted_ev": main_peak[0] + shift,
            "secondary_peak_shifted_ev": sec_peak[0] + shift,
        },
        "experiment_dielectric_function": {
            "source": "Aspnes & Studna, Phys. Rev. B 27, 985 (1983), <100> undoped InP, room temperature",
            "data_file": str(args.aspnes.name), "sha256": sha256(args.aspnes),
            "converted_csv": csv_path.name,
            "eps2_peaks_1p5_to_6_eV": exp_peaks_sorted[:4],
            "E1_ev": e1_exp, "eps2_maximum_E0prime_E2_region_ev": e2_exp,
            "literature_note": "E2 of InP is usually quoted near 5.0-5.1 eV; the tabulated eps2 peaks at 4.70 eV where E0' and E2 overlap",
        },
        "resonance_comparison": {
            "main_peak_shifted_minus_E1_ev": main_peak[0] + shift - e1_exp,
            "secondary_peak_shifted_minus_eps2_maximum_ev": sec_peak[0] + shift - e2_exp,
            "note": "with a single rigid shift fixed by the fundamental gap, both kernel resonances are compared to independent higher critical points",
        },
        "phonon_frequency_comparison_cm-1": {
            "calculated_Gamma_optical_TO_LO_degenerate": calc_freq_cm1,
            "bulk_Raman_TO": RAMAN_BULK_TO, "bulk_Raman_LO": RAMAN_BULK_LO,
            "calc_minus_bulk_TO_percent": 100 * (calc_freq_cm1 - RAMAN_BULK_TO) / RAMAN_BULK_TO,
            "nanowire_TO_Mante2020": NW_TO_THZ * THZ_TO_CM1, "nanowire_LO_Mante2020": NW_LO_THZ * THZ_TO_CM1,
            "calc_minus_nanowire_TO_percent": 100 * (calc_freq_cm1 - NW_TO_THZ * THZ_TO_CM1) / (NW_TO_THZ * THZ_TO_CM1),
        },
        "mechanism_check_Mante2020": {
            "source": "P.-A. Mante et al., ACS Photonics 7, 1923 (2020), arXiv:1909.02238; InP nanowires, 550 nm/35 fs pump, 720 nm probe",
            "finding": "coherent TO amplitude independent of doping (intrinsic to 4.6e19 cm-3) -> generated and detected by second-order processes; Reststrahlen-band modes scale with surface field (TDFS)",
            "relation_to_kernel": "the computed kernel is exactly the bulk second-order (Raman-type) generation channel; surface-field channels are outside its scope",
            "kernel_invariant_at_experimental_pumps": {
                "2.254 eV (Mante, 550 nm)": inv_at(PUMP_MANTE_EV),
                "2.0 eV (Pfeifer 1992 pump)": inv_at(PUMP_PFEIFER_EV),
                "3.10 eV (400 nm, near E1)": inv_at(3.10),
                "peak": main_peak[1],
            },
            "prediction": f"pumping near E1 (~{main_peak[0]+shift:.2f} eV) should drive the TO mode about {main_peak[1]/inv_at(PUMP_MANTE_EV):.1f}x more strongly than the 550 nm pump used by Mante et al.",
        },
        "known_model_mismatches": [
            "No measured pump-energy scan of a coherent phonon exists for bulk InP; the located experiments use one pump energy each.",
            "The calculation is Gamma-c only, scalar-relativistic (no spin-orbit; InP Delta0 = 0.11 eV), PBE bands with a rigid scissor, and 0.03 eV smearing.",
            "At exactly q = 0 the LO-TO splitting is not resolved; the kernel's three optical modes share the TO-like frequency.",
            "Nanowire (Mante 2020) and bulk differ: nanowire TO is red-shifted by ~7 cm-1 and field-enhancement/depolarization in ~100 nm wires affect absolute amplitudes.",
            "Excitonic effects are absent (weak in bulk InP, exciton binding ~5 meV).",
        ],
    }
    (args.output_dir / "metrics.json").write_text(json.dumps(metrics, indent=2) + "\n")

    # --- figure
    fig = plt.figure(figsize=(10.5, 10.5))
    gs = fig.add_gridspec(2, 2, height_ratios=[1.55, 1.0], hspace=0.62, wspace=0.28)
    ax = fig.add_subplot(gs[0, :])
    ax.plot(w_shift, inv / inv.max(), color="#0072B2", lw=2.0,
            label=f"calculated Γc kernel invariant, 96³ (photon axis shifted +{shift:.2f} eV = PBE gap error)")
    ax.plot(w, inv / inv.max(), color="#0072B2", lw=1.0, ls=":", alpha=0.6, label="same, unshifted (PBE scale)")
    ax.plot(e_exp, eps2 / eps2.max(), "o-", color="#111111", ms=3.5, lw=1.2,
            label="experiment: ε₂(ω) of bulk InP, ellipsometry (Aspnes & Studna 1983)")
    for e, lab, col in ((E_GAP_EXP_300K, "E₀ (gap)", "0.35"), (e1_exp, "E₁", "0.35"), (e2_exp, "ε₂ max (E₀′/E₂)", "0.35")):
        ax.axvline(e, color=col, lw=0.9, ls="--")
        ax.text(e, 1.02, lab, ha="center", va="bottom", fontsize=9, color="0.25")
    ax.axvline(PUMP_MANTE_EV, color="#009E73", lw=1.2, ls="-.")
    ax.text(PUMP_MANTE_EV, 0.62, " 550 nm pump\n (Mante 2020,\n coherent TO)", color="#009E73", fontsize=8, va="center")
    ax.set_xlim(0, 6.5)
    ax.set_ylim(0, 1.12)
    ax.set_xlabel("photon energy (eV, experimental scale)")
    ax.set_ylabel("normalized to peak")
    ax.set_title("Bulk InP: where the coherent-phonon generation kernel resonates versus the measured interband critical points")
    ax.grid(alpha=0.18)
    ax.legend(fontsize=8.2, loc="upper center", bbox_to_anchor=(0.5, -0.13), ncol=1, frameon=False)
    ax.text(0.99, 0.03,
            f"kernel peaks after the gap shift: {main_peak[0]+shift:.2f} and {sec_peak[0]+shift:.2f} eV\n"
            f"measured: E₁ = {e1_exp:.2f} eV, ε₂ maximum (E₀′/E₂ complex) = {e2_exp:.2f} eV\n"
            "one rigid shift fixed by the fundamental gap; no fitted scale, no fitted shift",
            transform=ax.transAxes, ha="right", va="bottom", fontsize=8.5,
            bbox=dict(facecolor="white", alpha=0.85, edgecolor="0.7"))

    ax2 = fig.add_subplot(gs[1, 0])
    items = [("calc. Γ optical mode\n(TO = LO at q=0, PBE)", calc_freq_cm1, "#0072B2"),
             ("bulk Raman TO\n(Mooradian & Wright 1966)", RAMAN_BULK_TO, "#111111"),
             ("bulk Raman LO", RAMAN_BULK_LO, "#111111"),
             ("nanowire TO, pump-probe & Raman\n(Mante 2020, 8.9 THz)", NW_TO_THZ * THZ_TO_CM1, "#009E73"),
             ("nanowire LO, Raman\n(Mante 2020, 10.3 THz)", NW_LO_THZ * THZ_TO_CM1, "#009E73")]
    for i, (lab, val, col) in enumerate(items):
        ax2.barh(i, val, color=col, alpha=0.85 if i == 0 else 0.55, height=0.6)
        ax2.text(val + 3, i, f"{val:.1f}", va="center", fontsize=8.5)
    ax2.set_yticks(range(len(items)))
    ax2.set_yticklabels([it[0] for it in items], fontsize=8)
    ax2.set_xlim(250, 380)
    ax2.invert_yaxis()
    ax2.set_xlabel("optical phonon frequency (cm⁻¹)")
    ax2.set_title("Phonon frequencies", fontsize=10)
    ax2.grid(alpha=0.18, axis="x")

    ax3 = fig.add_subplot(gs[1, 1])
    pumps = [("550 nm\n(Mante 2020)", PUMP_MANTE_EV), ("620 nm\n(2.0 eV, 1992)", PUMP_PFEIFER_EV),
             ("400 nm\n(3.10 eV)", 3.10), (f"E₁ resonance\n({main_peak[0]+shift:.2f} eV)", main_peak[0] + shift)]
    vals = [inv_at(p[1]) / main_peak[1] for p in pumps]
    ax3.bar(range(len(pumps)), vals, color=["#009E73", "0.55", "#D55E00", "#0072B2"])
    for i, v in enumerate(vals):
        ax3.text(i, v + 0.02, f"{v:.2f}", ha="center", fontsize=8.5)
    ax3.set_xticks(range(len(pumps)))
    ax3.set_xticklabels([p[0] for p in pumps], fontsize=8)
    ax3.set_ylim(0, 1.15)
    ax3.set_ylabel("predicted TO driving strength\n(kernel invariant, relative to peak)")
    ax3.set_title("Prediction at pump energies used in InP experiments", fontsize=10)
    ax3.grid(alpha=0.18, axis="y")

    fig.suptitle("InP coherent-phonon kernel versus experiment (2026-09-05): resonance positions, phonon frequencies, mechanism",
                 fontsize=11.5, y=0.995)
    fig.savefig(args.output_dir / "inp_experiment_vs_current.png", dpi=200, bbox_inches="tight")
    plt.close(fig)
    print(json.dumps({k: metrics[k] for k in ("scissor", "resonance_comparison", "phonon_frequency_comparison_cm-1")}, indent=2))
    print("E1/E2 from data:", e1_exp, e2_exp, "| exp eps2 peaks:", exp_peaks_sorted[:4])
    print("kernel at pumps:", metrics["mechanism_check_Mante2020"]["kernel_invariant_at_experimental_pumps"])


if __name__ == "__main__":
    main()
